//! Generates a rust_connect_library's `lib.rs` from proto descriptor sets.
//!
//! ```text
//! codegen --out lib.rs
//!         --generate <set>...        descriptor sets of the protos to generate
//!         --descriptor_set <set>...  every set their imports resolve against
//! ```
//!
//! connectrpc-codegen emits one file per proto package; they are nested into
//! a `pub mod` tree matching the package names, mirroring connectrpc-build's
//! include file but inlined, so the output is a single crate root.

use std::collections::{BTreeMap, HashSet};
use std::fmt::Write as _;
use std::path::PathBuf;

use anyhow::{Context, Result, anyhow, bail};
use buffa_codegen::generated::descriptor::{FileDescriptorProto, FileDescriptorSet};
use connectrpc_codegen::codegen::{self, GeneratedFileKind, Options};

struct Args {
    out: PathBuf,
    generate: Vec<PathBuf>,
    descriptor_sets: Vec<PathBuf>,
}

fn parse_args() -> Result<Args> {
    let mut out = None;
    let mut generate = Vec::new();
    let mut descriptor_sets = Vec::new();
    let mut args = std::env::args_os().skip(1);
    while let Some(flag) = args.next() {
        let value = args
            .next()
            .with_context(|| format!("{} needs a value", flag.to_string_lossy()))?;
        match flag.to_str() {
            Some("--out") => out = Some(PathBuf::from(value)),
            Some("--generate") => generate.push(PathBuf::from(value)),
            Some("--descriptor_set") => descriptor_sets.push(PathBuf::from(value)),
            _ => bail!("unknown flag {}", flag.to_string_lossy()),
        }
    }
    Ok(Args {
        out: out.context("--out is required")?,
        generate,
        descriptor_sets,
    })
}

fn read_descriptor_set(path: &PathBuf) -> Result<Vec<FileDescriptorProto>> {
    let bytes = std::fs::read(path).with_context(|| format!("reading {}", path.display()))?;
    // Descriptor sets come from protoc, so buffa's tooling bound applies
    // rather than its untrusted-input default.
    let options = buffa_codegen::tooling_decode_options().map_err(|e| anyhow!("{e}"))?;
    let set: FileDescriptorSet = options
        .decode_from_slice(&bytes)
        .map_err(|e| anyhow!("decoding {}: {e}", path.display()))?;
    Ok(set.file)
}

/// Nests each package's generated file under `pub mod` blocks named after
/// its dotted package.
fn module_tree(files: &[(String, String)]) -> String {
    #[derive(Default)]
    struct Node<'a> {
        contents: Vec<&'a str>,
        children: BTreeMap<&'a str, Node<'a>>,
    }

    let mut root = Node::default();
    for (package, content) in files {
        let mut node = &mut root;
        for segment in package.split('.').filter(|s| !s.is_empty()) {
            node = node.children.entry(segment).or_default();
        }
        node.contents.push(content);
    }

    // The same suppressions connectrpc-build puts on its module tree: buffa's
    // list plus the one the service stubs trip under edition 2024. Doc
    // comments are copied from proto comments as their authors wrote them,
    // and third-party protos such as Kubernetes' indent with tabs.
    let allow = buffa_codegen::ALLOW_LINTS
        .iter()
        .copied()
        .chain([
            "impl_trait_redundant_captures",
            "clippy::tabs_in_doc_comments",
        ])
        .collect::<Vec<_>>()
        .join(", ");

    fn emit(out: &mut String, node: &Node, allow: &str) {
        for content in &node.contents {
            out.push_str(content);
            out.push('\n');
        }
        for (name, child) in &node.children {
            let ident = buffa_codegen::idents::escape_mod_ident(name);
            writeln!(out, "#[allow({allow})]\npub mod {ident} {{\nuse super::*;").unwrap();
            emit(out, child, allow);
            out.push_str("}\n");
        }
    }

    let mut out = String::from("// @generated by //bazel/connect/codegen. DO NOT EDIT.\n\n");
    emit(&mut out, &root, &allow);
    out
}

fn main() -> Result<()> {
    let args = parse_args()?;

    // Transitive sets overlap wherever two protos share an import.
    let mut seen = HashSet::new();
    let mut pool = Vec::new();
    for path in &args.descriptor_sets {
        for file in read_descriptor_set(path)? {
            if seen.insert(file.name.clone()) {
                pool.push(file);
            }
        }
    }

    let mut to_generate = Vec::new();
    for path in &args.generate {
        for file in read_descriptor_set(path)? {
            to_generate.extend(file.name);
        }
    }

    let mut options = Options::default();
    options.buffa.file_per_package = true;
    let generated = codegen::generate_files(&pool, &to_generate, &options)?;

    let packages: Vec<(String, String)> = generated
        .into_iter()
        .filter(|f| f.kind == GeneratedFileKind::PackageMod)
        .map(|f| (f.package, f.content))
        .collect();

    std::fs::write(&args.out, module_tree(&packages))
        .with_context(|| format!("writing {}", args.out.display()))
}
