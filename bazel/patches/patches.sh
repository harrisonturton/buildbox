#!/usr/bin/env bash
#
# Keeps our changes to an external Cargo workspace as a series of patches,
# one per commit, applied by crate_universe on top of an upstream commit.
#
# Usage:
#   patches.sh checkout <dir> <checkout>   clone upstream and replay the series
#   patches.sh export <dir> <checkout>     render the checkout's commits back
#
# <dir> is the package holding the series, such as third_party/starlark. Its
# UPSTREAM file names the upstream repository and the commit the series
# applies to. Each commit becomes one patch per crate it touches, under
# <dir>/patches/<crate>/, keeping its message and author, and export
# regenerates <dir>/patches.MODULE.bazel, which hands them to crate_universe,
# and repins crate_universe's lockfile.
#
# In the checkout, the `upstream` branch marks the base and `buildbox` holds
# our commits. To move to a new upstream release, rebase `buildbox` onto it,
# point `upstream` at it, export, and bump the crate versions to match.
#
# Patches apply to the crates as published, whose Cargo.toml is rewritten by
# `cargo publish`, so commits must not touch Cargo.toml.

set -euo pipefail

usage() {
  echo "usage: $0 checkout|export <dir> <checkout>" >&2
  exit 2
}

[[ $# -eq 3 ]] || usage
readonly command="$1" checkout="$(realpath -m "$3")"
cd "$(git rev-parse --show-toplevel)"
readonly dir="${2%/}"
readonly upstream_file="$dir/UPSTREAM"

upstream_field() {
  awk -v key="$1" '$1 == key { print $2 }' "$upstream_file"
}

checkout() {
  local url commit
  url="$(upstream_field url)"
  commit="$(upstream_field commit)"
  if [[ -e "$checkout" ]]; then
    echo "$checkout already exists" >&2
    exit 1
  fi
  git clone -q "$url" "$checkout"
  git -C "$checkout" checkout -q -b buildbox "$commit"
  git -C "$checkout" branch -q upstream "$commit"

  local numbers number
  numbers="$(find "$dir/patches" -name '*.patch' -printf '%f\n' | cut -d- -f1 | sort -u)"
  for number in $numbers; do
    apply_commit "$number"
  done
  echo "Replayed $(git -C "$checkout" rev-list --count upstream..buildbox) commits onto $commit in $checkout"
}

# Applies the patches numbered <number>, one per crate, as a single commit.
apply_commit() {
  local number="$1" first=1 patch crate
  for patch in "$dir"/patches/*/"$number"-*.patch; do
    crate="$(basename "$(dirname "$patch")")"
    if [[ $first -eq 1 ]]; then
      git -C "$checkout" am -q --directory="$crate" "$(realpath "$patch")"
      first=0
    else
      git -C "$checkout" apply --index --directory="$crate" "$(realpath "$patch")"
      git -C "$checkout" commit -q --amend --no-edit
    fi
  done
}

export_series() {
  local base
  base="$(git -C "$checkout" rev-parse upstream)"
  check_series "$base"

  rm -rf "$dir/patches"
  local number=1 commit crate
  for commit in $(git -C "$checkout" rev-list --reverse upstream..HEAD); do
    for crate in $(crates_touched "$commit"); do
      git -C "$checkout" format-patch -q -1 --no-numbered --zero-commit \
        --no-signature --relative="$crate" --start-number="$number" \
        -o "$PWD/$dir/patches/$crate" "$commit"
    done
    number=$((number + 1))
  done

  sed -i "s/^commit .*/commit $base/" "$upstream_file"
  write_module > "$dir/patches.MODULE.bazel"
  echo "Exported $((number - 1)) commits to $dir/patches"
  repin
}

# crate_universe's lockfile records each crate's patches, so it changes as
# the series does.
repin() {
  echo "Repinning crates for the new list of patches"
  CARGO_BAZEL_REPIN=1 bazel fetch --noshow_progress @crates//... 2>&1 | grep -v '^INFO:' || true
}

# Fails unless upstream..HEAD is a line of commits that patches can express.
check_series() {
  local base="$1"
  if [[ -n "$(git -C "$checkout" rev-list --merges "$base..HEAD")" ]]; then
    echo "upstream..HEAD has merge commits; rebase them away" >&2
    exit 1
  fi
  local path
  for path in $(git -C "$checkout" diff --name-only "$base" HEAD); do
    if [[ "$path" != */* ]]; then
      echo "$path is outside every crate, so no patch can carry it" >&2
      exit 1
    fi
    if [[ "$(basename "$path")" == Cargo.toml ]]; then
      echo "$path: published crates rewrite Cargo.toml, so patches can't touch it" >&2
      exit 1
    fi
  done
}

crates_touched() {
  git -C "$checkout" diff-tree --no-commit-id --name-only -r "$1" | cut -d/ -f1 | sort -u
}

write_module() {
  cat <<EOF
"""Generated by bazel/patches/patches.sh from $dir/patches: don't edit.

Applies our commits to the upstream crates, one patch per commit.
"""

crate = use_extension("@rules_rust//crate_universe:extensions.bzl", "crate")
EOF
  local crate_dir patch
  for crate_dir in "$dir"/patches/*/; do
    printf '\ncrate.annotation(\n    crate = "%s",\n' "$(basename "$crate_dir")"
    printf '    patch_args = ["-p1"],\n    patches = [\n'
    for patch in "$crate_dir"*.patch; do
      printf '        "//%s:%s",\n' "$dir" "${patch#"$dir"/}"
    done
    printf '    ],\n)\n'
  done
}

case "$command" in
  checkout) checkout ;;
  export) export_series ;;
  *) usage ;;
esac
